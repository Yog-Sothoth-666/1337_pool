int	ft_strcmp(char *s1, char *s2)
{
	int	val;

	val = 0;
	while (*s1 || *s2)
	{
		val = *s1 - *s2;
		if (val != 0)
			return (val);
		s1++;
		s2++;
	}
	return (val);
}
