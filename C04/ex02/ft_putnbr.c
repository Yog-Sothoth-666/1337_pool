#include <unistd.h>

void	ft_putnbr(int nb)
{
	char	ld;

	if (nb < 0)
	{
		write(1, "-", 1);
		if (nb <= -10)
			ft_putnbr(nb / -10);
		ld = '0' - nb % 10;
		write(1, &ld, 1);
	}
	else
	{
		if (nb >= 10)
			ft_putnbr(nb / 10);
		ld = '0' + nb % 10;
		write(1, &ld, 1);
	}
}
