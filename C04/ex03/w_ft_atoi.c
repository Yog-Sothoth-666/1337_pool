int	ft_atoi(char *str)
{
	int	n;
	int	s;

	s = 1;
	n = 0;
	while (*str)
	{
		if (*str == '-')
			s *= -1;
		else if (*str == ' ' || *str == '+')
		{
			str++;
			continue ;
		}
		else if (*str < '0' || *str > '9')
			break ;
		else
		{
			n *= 10;
			n += *str - '0';
		}
		str++;
	}
	n *= s;
	return (n);
}
