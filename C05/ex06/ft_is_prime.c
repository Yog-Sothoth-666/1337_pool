#include <stdio.h>

int	ft_is_prime(int nb)
{
	int i;
	int n;

	i = 1;
	n = 0;
	while (i <= nb / i)
	{
		if (nb % i == 0)
			n++;
		i++;
	}
	if (n == 1)
		return (1);
	else
		return (0);
}

int main()
{
	printf("%d", ft_is_prime(98));
}
